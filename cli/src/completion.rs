//! The zsh completion script, built from the command definition rather than transcribed.
//!
//! Two things are generated and one is declared. Generated: the subcommand tree, every long flag, and
//! the members of each closed set. Declared: the arguments whose values live on the bus, in
//! `providers` below, keyed by command path and argument. A key that names no real command or
//! argument fails the tests, because the emitter resolves every key against the tree it walks.

use clap::{Arg, Command};

/// Where the values of one argument come from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Provider {
    /// Addresses that hold a record, and the addresses of live participants.
    Addresses,
    /// Topics that hold a cursor of the caller.
    Topics,
    /// Consumer names the caller owns.
    Consumers,
    /// Files, which the shell already knows how to list.
    Files,
    /// Directories.
    Directories,
    /// Suggested spellings that do not restrict the value.
    Hint(&'static [&'static str]),
}

/// The arguments whose values are not known to the definition.
///
/// The empty path is the top-level command, so `("", "--db")` is the global database argument.
pub const PROVIDERS: &[(&str, &str, Provider)] = &[
    ("", "db", Provider::Files),
    ("publish", "address", Provider::Addresses),
    ("ask", "address", Provider::Addresses),
    ("read", "addresses", Provider::Addresses),
    ("follow", "addresses", Provider::Addresses),
    ("await", "target", Provider::Addresses),
    ("consumers", "topic", Provider::Topics),
    ("consumers rm", "topic", Provider::Topics),
    ("cursor get", "consumer", Provider::Consumers),
    ("cursor get", "topic", Provider::Topics),
    ("cursor set", "consumer", Provider::Consumers),
    ("cursor set", "topic", Provider::Topics),
    ("cursor reset", "consumer", Provider::Consumers),
    ("cursor reset", "topic", Provider::Topics),
    ("card", "cwd", Provider::Directories),
    ("publish", "ack", Provider::Hint(ACK_HINTS)),
    ("publish", "reply-to", Provider::Addresses),
    ("prune", "older-than", Provider::Hint(AGE_HINTS)),
];

const ACK_HINTS: &[&str] = &[
    "true",
    "received",
    "started",
    "completed",
    "received,started,completed",
];
const AGE_HINTS: &[&str] = &["1h", "6h", "1d", "7d"];

/// The whole script, for the command definition passed in.
pub fn script(root: &Command) -> String {
    let mut out = String::new();
    out.push_str("#compdef msgq\n");
    out.push_str("# Generated by `msgq completions zsh`. Edit the definition, not this file.\n\n");
    out.push_str(&helpers());
    out.push_str(&dispatch(root));
    for command in subcommands(root) {
        let name = command.get_name().to_string();
        emit_command(&mut out, &command, &name);
    }
    out
}

fn subcommands(command: &Command) -> Vec<Command> {
    command
        .get_subcommands()
        .filter(|sub| sub.get_name() != "help")
        .cloned()
        .collect()
}

fn dispatch(root: &Command) -> String {
    let mut out = String::new();
    out.push_str("_msgq() {\n  local -a commands\n  commands=(\n");
    for command in subcommands(root) {
        out.push_str(&format!(
            "    '{}:{}'\n",
            command.get_name(),
            zsh_quote(&one_line(command.get_about()))
        ));
    }
    out.push_str("  )\n");
    let mut specs: Vec<String> = root
        .get_arguments()
        .filter(|arg| arg.get_id() == "db")
        .map(|db| spec_for(db, "", true))
        .collect();
    specs.push("1: :->command".to_string());
    specs.push("*::argument:->arguments".to_string());
    out.push_str("  _arguments -C \\\n");
    out.push_str(&format!("    '{}'\n\n", specs.join("' \\\n    '")));
    out.push_str("  case $state in\n");
    out.push_str("    command) _describe 'command' commands ;;\n");
    out.push_str("    arguments)\n      case $words[1] in\n");
    for command in subcommands(root) {
        out.push_str(&format!(
            "        {}) _msgq_{} ;;\n",
            command.get_name(),
            command.get_name()
        ));
    }
    out.push_str("      esac\n    ;;\n  esac\n}\n\n");
    out
}

/// One function per command, with its own `_arguments` call.
fn emit_command(out: &mut String, command: &Command, path: &str) {
    let subs = subcommands(command);
    if !subs.is_empty() && command.get_arguments().next().is_none() {
        // A pure dispatcher: offer its subcommands and hand over.
        out.push_str(&format!("_msgq_{}() {{\n  local -a subs\n  subs=(\n", path));
        for sub in &subs {
            out.push_str(&format!(
                "    '{}:{}'\n",
                sub.get_name(),
                zsh_quote(&one_line(sub.get_about()))
            ));
        }
        out.push_str("  )\n  _describe 'subcommand' subs\n}\n\n");
        for sub in subs {
            emit_command(out, &sub, &format!("{} {}", path, sub.get_name()));
        }
        return;
    }

    let function = path.replace(' ', "_");
    let mut specs: Vec<String> = Vec::new();
    if !subs.is_empty() {
        specs.push("1: :->subcommand".to_string());
    }
    let mut slot = 0;
    for arg in command.get_arguments() {
        if arg.get_id() == "help" || arg.get_id() == "version" {
            continue;
        }
        if arg.get_long().is_none() {
            // A positional: the slot is its place in the definition, and the value follows the table.
            slot += 1;
            specs.push(format!("{slot}:{}", positional_action(arg, path)));
            continue;
        }
        // A flag that takes no value is completed as a flag, not as `--flag=(true false)`.
        if !arg.get_action().takes_values() {
            let help = one_line(arg.get_help());
            let label = if help.is_empty() {
                arg.get_long().unwrap_or_default().to_string()
            } else {
                zsh_quote(&help)
            };
            specs.push(format!("--{}[{label}]", arg.get_long().unwrap_or_default()));
            continue;
        }
        specs.push(spec_for(arg, path, false));
    }
    out.push_str(&format!("_msgq_{function}() {{\n"));
    if specs.is_empty() {
        out.push_str("  _arguments '*: :'\n");
    } else {
        out.push_str("  _arguments \\\n");
        out.push_str(&format!("    '{}'\n", specs.join("' \\\n    '")));
    }
    if !subs.is_empty() {
        out.push_str("  case $state in\n    subcommand)\n      local -a subs\n      subs=(\n");
        for sub in &subs {
            out.push_str(&format!(
                "        '{}:{}'\n",
                sub.get_name(),
                zsh_quote(&one_line(sub.get_about()))
            ));
        }
        out.push_str("      )\n      _describe 'subcommand' subs ;;\n  esac\n");
    }
    out.push_str("}\n\n");

    for sub in subs {
        emit_command(out, &sub, &format!("{} {}", path, sub.get_name()));
    }
}

/// One `_arguments` spec: `--flag[help]:value:action`.
fn spec_for(arg: &Arg, command_path: &str, global: bool) -> String {
    let long = arg.get_long().unwrap_or("db");
    let help = zsh_quote(&one_line(arg.get_help()));
    // The same spelling at every level: a flag is `--name[what it does]`, wherever it is declared.
    let _ = global;
    let spec = format!("--{long}[{help}]");

    // A flag is keyed by its long name, a positional by its id: both are what a caller types.
    let key = arg.get_long().unwrap_or(arg.get_id().as_str()).to_string();
    let action = match provider_for(command_path, &key) {
        Some(provider) => action_for(provider, command_path, &key),
        None => match arg.get_value_names() {
            // A value the definition knows: the closed set a ValueEnum produces.
            Some(_) if !possible_values(arg).is_empty() => {
                format!(":{}:({})", value_name(arg), possible_values(arg).join(" "))
            }
            // A free value, or a flag that takes none.
            Some(_) => format!(":{}:", value_name(arg)),
            None => String::new(),
        },
    };
    format!("{spec}{action}")
}

/// A positional's spec is `index:name:action`, and its name is what a caller sees.
fn positional_action(arg: &Arg, command_path: &str) -> String {
    let key = arg.get_id().as_str();
    let name = value_name(arg);
    match provider_for(command_path, key) {
        Some(provider) => match provider {
            Provider::Addresses => format!("{name}:_msgq_offer_addresses"),
            Provider::Topics => format!("{name}:_msgq_offer_topics"),
            Provider::Consumers => format!("{name}:_msgq_offer_consumers"),
            Provider::Files => format!("{name}:_files"),
            Provider::Directories => format!("{name}:_files -/"),
            Provider::Hint(_) => format!("{name}:_msgq_hint_{}", hint_name(command_path, key)),
        },
        // A positional with a closed set completes to its members, like a flag with one.
        None if !possible_values(arg).is_empty() => {
            format!("{name}:({})", possible_values(arg).join(" "))
        }
        None => name,
    }
}

fn action_for(provider: Provider, command_path: &str, arg_id: &str) -> String {
    match provider {
        Provider::Addresses => ":address:_msgq_offer_addresses".to_string(),
        Provider::Topics => ":topic:_msgq_offer_topics".to_string(),
        Provider::Consumers => ":consumer:_msgq_offer_consumers".to_string(),
        Provider::Files => ":file:_files".to_string(),
        Provider::Directories => ":directory:_files -/".to_string(),
        Provider::Hint(_) => format!(":value:_msgq_hint_{}", hint_name(command_path, arg_id)),
    }
}

/// The helper that offers a pattern value's common spellings.
fn hint_name(command_path: &str, arg_id: &str) -> String {
    let path = if command_path.is_empty() {
        "msgq".to_string()
    } else {
        command_path.replace(' ', "_")
    };
    format!("{path}_{}", arg_id.replace('-', "_"))
}

fn provider_for(command_path: &str, arg_id: &str) -> Option<Provider> {
    PROVIDERS
        .iter()
        .find(|(path, id, _)| *path == command_path && *id == arg_id)
        .map(|(_, _, provider)| *provider)
}

fn possible_values(arg: &Arg) -> Vec<String> {
    arg.get_possible_values()
        .iter()
        .map(|value| value.get_name().to_string())
        .collect()
}

fn value_name(arg: &Arg) -> String {
    arg.get_value_names()
        .and_then(|names| names.first().map(|name| name.to_string()))
        .unwrap_or_else(|| "value".to_string())
}

/// The three helpers a tab calls, and what they do when the bus is unreachable.
///
/// A pattern argument is offered but never restricted: `--ack` accepts a phase list this table does
/// not propose, so the helper adds suggestions without closing the value.
fn helpers() -> String {
    let mut out = String::new();
    out.push_str("_msgq_offer_addresses() {\n");
    out.push_str("  local -a found\n");
    out.push_str("  found=(${(f)\"$(msgq topics --names 2>/dev/null)\"})\n");
    out.push_str("  found+=(${(f)\"$(msgq sessions --names 2>/dev/null)\"})\n");
    out.push_str("  _describe 'address' found\n}\n\n");
    out.push_str("_msgq_offer_topics() {\n");
    out.push_str("  local -a found\n");
    out.push_str("  found=(${(f)\"$(msgq topics --names 2>/dev/null)\"})\n");
    out.push_str("  _describe 'topic' found\n}\n\n");
    out.push_str("_msgq_offer_consumers() {\n");
    out.push_str("  local -a found\n");
    out.push_str("  found=(${(f)\"$(msgq consumers --names 2>/dev/null)\"})\n");
    out.push_str("  _describe 'consumer' found\n}\n\n");
    for (path, id, provider) in PROVIDERS {
        if let Provider::Hint(values) = provider {
            out.push_str(&format!(
                "_msgq_hint_{}() {{ compadd -S '' -- {} }}\n\n",
                hint_name(path, id),
                values
                    .iter()
                    .map(|value| format!("'{}'", zsh_quote(value)))
                    .collect::<Vec<_>>()
                    .join(" ")
            ));
        }
    }
    out
}

/// Single-quoted for zsh: a quote or a newline in help text must not break the script.
pub fn zsh_quote(raw: &str) -> String {
    raw.replace('\\', "\\\\")
        .replace('\'', "'\\''")
        .replace('\n', " ")
}

fn one_line(about: Option<&clap::builder::StyledStr>) -> String {
    about
        .map(|text| text.to_string())
        .unwrap_or_default()
        .replace('\n', " ")
        .trim()
        .to_string()
}
